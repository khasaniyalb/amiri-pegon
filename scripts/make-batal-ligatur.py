#!/usr/bin/env python3
"""Writes sources/batal_ligatur.fea from sources/batal-ligatur.txt.

For every listed pattern, when at least one mark (harakat) sits inside the letter sequence,
an invisible zero-width blocker glyph (zerowidthspace) is inserted at the marked position ("|") early in `ccmp`. The ZWJ glyph
sits between the two letters, so the contextual ligature rules that need the letters to be
adjacent no longer match; the joining forms are unchanged (same result as typing a real ZWJ).
"""
import itertools, os, re, sys, unicodedata

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC = os.path.join(ROOT, "sources")
GLYPHS = os.path.join(SRC, "Amiri.glyphspackage", "glyphs")
MAXMARKS = 2            # marks allowed after each letter of a pattern
ZWJ = "zerowidthspace"   # empty, zero-width, not a mark (the real ZWJ glyph has a visible outline)


def read_glyph_map():
    cmap, marks = {}, []
    for fn in os.listdir(GLYPHS):
        t = open(os.path.join(GLYPHS, fn), encoding="utf-8").read()
        m = re.search(r'glyphname = "?([^";\n]+)"?;', t)
        u = re.search(r'\nunicode = "?([0-9A-Fa-f,]+)"?;', t)
        if not m or not u:
            continue
        name = m.group(1)
        for k, cp in enumerate(u.group(1).split(",")):
            c = int(cp, 16)
            cmap.setdefault(c, name)
            if k == 0 and unicodedata.category(chr(c)) == "Mn" and (0x600 <= c <= 0x6FF or 0x750 <= c <= 0x77F or 0x8A0 <= c <= 0x8FF):
                marks.append(name)
    return cmap, sorted(set(marks))


def read_joiners():
    out = []
    for line in open(os.path.join(SRC, "basic.fea"), encoding="utf-8"):
        m = re.match(r"\s*sub (\S+) by (\S+)\.fina;", line)
        if m and m.group(1) == m.group(2):
            out.append(m.group(1))
    return sorted(set(out))


def parse(path, cmap):
    pats = []
    for n, line in enumerate(open(path, encoding="utf-8"), 1):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        if ":" in line:
            line = line.rsplit(":", 1)[1].strip()
        toks = re.findall(r"\[[^\]]*\]|\S", line)
        follow = "*"
        if toks and toks[-1] in "+-" and len(toks[-1]) == 1:
            follow = toks.pop()
        slots, zpos = [], []
        for t in toks:
            if t == "|":
                if not slots:
                    raise SystemExit("%s:%d: '|' tidak boleh di awal" % (path, n))
                zpos.append(len(slots) - 1)
                continue
            chars = [c for c in (t[1:-1] if t.startswith("[") else t) if not c.isspace()]
            names = []
            for c in chars:
                if ord(c) not in cmap:
                    raise SystemExit("%s:%d: huruf %r tidak ada di font" % (path, n, c))
                names.append(cmap[ord(c)])
            slots.append(names)
        if len(slots) < 2 or not zpos:
            raise SystemExit("%s:%d: pola butuh minimal dua huruf dan satu tanda '|'" % (path, n))
        if zpos[-1] >= len(slots) - 1 + 1:
            raise SystemExit("%s:%d: '|' di luar pola" % (path, n))
        pats.append((slots, sorted(set(zpos)), follow, n))
    return pats


def cls(names):
    return names[0] if len(names) == 1 else "[" + " ".join(names) + "]"


def main():
    cmap, marks = read_glyph_map()
    joiners = read_joiners()
    pats = parse(os.path.join(SRC, "batal-ligatur.txt"), cmap)
    out = ["# GENERATED by scripts/make-batal-ligatur.py from sources/batal-ligatur.txt. Do not edit.",
           "@BL_Marks = [%s];" % " ".join(marks),
           "@BL_Join = [%s];" % " ".join(joiners), ""]
    letters = sorted({g for slots, *_ in pats for s in slots for g in s})
    out.append("lookup BL_Ins {")
    for g in letters + marks:
        out.append("    sub %s by %s %s;" % (g, g, ZWJ))
    out.append("} BL_Ins;\n")
    out.append("lookup BL_Rules {")
    count = 0
    for slots, zpos, follow, ln in pats:
        out.append("    # line %d" % ln)
        for masks in itertools.product(range(MAXMARKS + 1), repeat=len(slots)):
            if not any(masks):
                continue
            seq, last = [], []
            for k, s in enumerate(slots):
                seq.append(cls(s))
                seq += ["@BL_Marks"] * masks[k]
                last.append(len(seq) - 1)
            first, lastp = last[zpos[0]], last[zpos[-1]]
            targets = {last[z] for z in zpos}
            parts = []
            for i, t in enumerate(seq):
                if i < first or i > lastp:
                    parts.append(t)
                else:
                    parts.append(t + "'" + (" lookup BL_Ins" if i in targets else ""))
                if i == len(seq) - 1:
                    pass
            body_plain = [t + "'" if first <= i <= lastp else t for i, t in enumerate(seq)]
            if follow == "+":
                out.append("    sub %s @BL_Join;" % " ".join(parts[:first] + parts[first:lastp + 1] + parts[lastp + 1:]))
                count += 1
            elif follow == "-":
                out.append("    ignore sub %s @BL_Join;" % " ".join(body_plain))
                out.append("    sub %s;" % " ".join(parts))
                count += 1
            else:
                out.append("    sub %s;" % " ".join(parts))
                count += 1
    out.append("} BL_Rules;\n")
    out.append("feature ccmp {\n    lookup BL_Rules;\n} ccmp;\n")
    open(os.path.join(SRC, "batal_ligatur.fea"), "w", encoding="utf-8").write("\n".join(out))
    print("batal_ligatur.fea: %d pola, %d aturan" % (len(pats), count))


if __name__ == "__main__":
    main()
