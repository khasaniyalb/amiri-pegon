#!/usr/bin/env python3
# Writes sources/tashkil_context.fea: context-dependent tashkil shifts that glyph anchors cannot
# express (the same glyph is used next to many different letters). Run after a build:
#
#   python3 scripts/make-tashkil-context.py fonts/Amiri-Regular.ttf build/Amiri-Regular.ufo
#
# The rules sit after the generated `mark` lookups (see the "# Automatic Code" marker in
# Amiri.fea), so they act on the final mark positions. HarfBuzz propagates the offset of a mark
# to the marks attached to it (shadda -> vowel), so only the mark attached to the base is shifted.
import re, sys
from fontTools.ttLib import TTFont
from ufoLib2 import Font

SHIFTS = {            # name: (x, y) in font units
    "RAISE_TEH":  (0, 314),    # teh before kaf: mark above the end of the kaf stroke, like theh
    "RAISE_NOON": (0, 247),    # noon before kaf: same height as theh
    "LOWER_BEH":  (0, -190),   # beh before kaf: nestle under the end of the kaf stroke, like yeh
    "HAH_RIGHT":  (140, 0),    # hah/jeem/kha after lam.init.LamHaaInit: mark over the hah body
    "MEEM_KASRA": (0, -140),   # meem after lam, before final yeh: kasra below the bowl of the yeh
    "MEEM_UP":    (0, 160),    # meem after lam, before final alef: mark above the tips of both stems
    "NEXT_LEFT":  (-100, 0),   # letter after feh+hah/jeem/kha: its mark continues the staircase to the left
    "BIG_SHIFT":  (30, 60),    # damma/dammatan of that hah/jeem/kha, when a letter follows: clear the dot of the next letter
}


def main(ttf, ufo, out="sources/tashkil_context.fea"):
    go = TTFont(ttf).getGlyphOrder(); have = set(go)
    f = Font.open(ufo, validate=False)
    ta = [g.name for g in f if g.name in have and any(a.name == "_TashkilAbove" for a in g.anchors)]
    tb = [g.name for g in f if g.name in have and any(a.name == "_TashkilBelow" for a in g.anchors)]
    kaf = [n for n in go if re.match(r"^(kaf|keheh|gaf|kafD_otbelow|kafDotbelow|ng)[^.]*-ar\.medi(\.|$)", n)]
    hah = [n for n in go if re.match(r"^[^a][^.]*-ar\.fina\.AboveHaaIsol2(\..*)?$", n)]
    yeh = [n for n in go if re.match(r"^(yeh|alefMaksura|yehFarsi|yehbarree)[^.]*-ar\.fina$", n)]
    L = []
    cls = lambda n, g: L.append("@%s = [%s];" % (n, " ".join(g)))
    L += ["# Generated by scripts/make-tashkil-context.py -- do not edit by hand.", ""]
    cls("CTX_ABOVE", ta); cls("CTX_BELOW", tb); cls("CTX_ALL", ta + tb)
    cls("CTX_KAF", kaf); cls("CTX_HAH", hah); cls("CTX_YEH", yeh)
    alef = [n for n in ("alef-ar.fina",) if n in have]
    ffol = [n for n in go if re.match(r"^[^a][^.]*-ar\.medi\.FaaHaaInit(\..*)?$", n)]
    nxt = [n for n in go if re.match(r"^[^a][^.]*-ar\.(medi|fina)(\..*)?$", n) and n not in set(ta + tb)]
    big = [n for n in ("damma-ar", "dammatan-ar") if n in ta]
    cls("CTX_ALEF", alef); cls("CTX_FFOL", ffol); cls("CTX_NEXT", nxt); cls("CTX_BIG", big)
    L.append("")
    for k, (x, y) in SHIFTS.items():
        tgt = "@CTX_BELOW" if k == "MEEM_KASRA" else ("@CTX_BIG" if k == "BIG_SHIFT" else "@CTX_ABOVE")
        L.append("lookup CTX_%s { pos %s <%d %d 0 0>; } CTX_%s;" % (k, tgt, x, y, k))
    L += ["", "feature mark {"]

    def chain(base, T, lk, nxt, other):
        """Shift the mark(s) of class T attached to `base`, when `nxt` follows.
        `other` = marks of the opposite side that may sit in between. Marks stacked on the
        same base are positioned independently (a vowel is not carried along by its shadda), so
        every T mark in the cluster is shifted."""
        S = "%s' lookup %s" % (T, lk)
        L.append("    pos %s %s %s;" % (base, S, nxt))                    # one mark
        L.append("    pos %s %s %s %s;" % (base, S, S, nxt))              # two stacked marks
        L.append("    pos %s %s %s %s;" % (base, other, S, nxt))          # other-side mark first
        L.append("    pos %s %s %s %s;" % (base, S, other, nxt))          # other-side mark last
        L.append("    pos %s %s %s %s %s;" % (base, other, S, S, nxt))    # other-side first, then two

    for letters, lk, comment in ((["teh-ar.init"], "CTX_RAISE_TEH", "teh before kaf"),
                                 (["noon-ar.init"], "CTX_RAISE_NOON", "noon before kaf"),
                                 (["beh-ar.init"], "CTX_LOWER_BEH", "beh before kaf")):
        if not all(n in have for n in letters): continue
        L.append("    # %s" % comment)
        b = "[%s]" % " ".join(letters)
        chain(b, "@CTX_ABOVE", lk, "@CTX_KAF", "@CTX_BELOW")
    # lam + hah/jeem/kha: shift the mark(s) of the hah to the right (marks between lam and hah allowed)
    if "lam-ar.init.LamHaaInit" in have:
        L.append("    # marks of hah/jeem/kha after lam.init.LamHaaInit")
        T = "@CTX_ABOVE' lookup CTX_HAH_RIGHT"
        for head in ("[lam-ar.init.LamHaaInit] @CTX_HAH", "[lam-ar.init.LamHaaInit] @CTX_ALL @CTX_HAH"):
            L.append("    pos %s %s;" % (head, T))
            L.append("    pos %s %s %s;" % (head, T, T))
            L.append("    pos %s @CTX_BELOW %s;" % (head, T))
            L.append("    pos %s @CTX_BELOW %s %s;" % (head, T, T))
    # meem after lam, before final yeh: kasra below the bowl of the yeh
    meem = [n for n in ("meem-ar.medi.LamMemInit", "meem-ar.medi.LamMemInitTatweel") if n in have]
    if meem:
        L.append("    # kasra of meem.medi.LamMemInit before final yeh")
        b = "[%s]" % " ".join(meem)
        chain(b, "@CTX_BELOW", "CTX_MEEM_KASRA", "@CTX_YEH", "@CTX_ABOVE")
    if "meem-ar.medi.LamMemInit" in have and alef:
        L.append("    # mark of meem.medi.LamMemInit before final alef: above the tips of both stems")
        chain("[meem-ar.medi.LamMemInit]", "@CTX_ABOVE", "CTX_MEEM_UP", "@CTX_ALEF", "@CTX_BELOW")
    if ffol:
        L.append("    # after feh + hah/jeem/kha with more letters: marks of the next letter shift left")
        T = "@CTX_ABOVE' lookup CTX_NEXT_LEFT"
        for head in ("@CTX_FFOL @CTX_NEXT", "@CTX_FFOL @CTX_ALL @CTX_NEXT", "@CTX_FFOL @CTX_ALL @CTX_ALL @CTX_NEXT"):
            for tail in (T, "%s %s" % (T, T), "@CTX_BELOW %s" % T, "@CTX_BELOW %s %s" % (T, T)):
                L.append("    pos %s %s;" % (head, tail))
        L.append("    # damma/dammatan of that hah/jeem/kha: a little up and to the right")
        L.append("    pos @CTX_FFOL @CTX_BIG' lookup CTX_BIG_SHIFT @CTX_NEXT;")
        L.append("    pos @CTX_FFOL @CTX_ALL @CTX_BIG' lookup CTX_BIG_SHIFT @CTX_NEXT;")
    L += ["} mark;", ""]
    open(out, "w").write("\n".join(L))
    print("wrote", out, len(L), "lines")


if __name__ == "__main__":
    main(*sys.argv[1:])
